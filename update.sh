#!/bin/bash
# update.sh - pasang versi terbaru XAUUSD Signal Bot.
set -euo pipefail
EXPECTED_SHA=5883d039fac077f5
FILE_COUNT=23
echo "XAUUSD Signal Bot - pembaruan"
echo "========================================"
if [ ! -d .git ]; then echo "  [X] Bukan folder repo git. Posisi: $(pwd)"; exit 1; fi
echo "  [ok] folder repo : $(pwd)"
BACKUP=""
if [ -f .env ]; then BACKUP=$(mktemp); cp .env "$BACKUP"; echo "  [ok] .env         dicadangkan";
