rm -rf "$TMP"
if [ -n "$BACKUP" ]; then cp "$BACKUP" .env; rm -f "$BACKUP"; fi
chmod +x install-macos.sh 2>/dev/null || true
echo "  [ok] $FILE_COUNT berkas ditulis"
echo "========================================"
echo
for f in telegram_bot.py .github/workflows/commands.yml; do
  if [ -f "$f" ]; then echo "  [ok] $f"; else echo "  [X]  $f HILANG"; fi
done
echo
echo "Berikutnya:  git add -A && git commit -m 'feat: latensi per perintah' && git push"
exit 0

