#!/bin/bash
# update.sh - pasang versi terbaru XAUUSD Signal Bot.
# Skrip ini berisi seluruh berkas di dalamnya.
#
# Pakai:  cd ke folder repo Anda, lalu:  bash update.sh
# .env dan .git Anda TIDAK tersentuh.

set -euo pipefail

EXPECTED_SHA=ddbae32b79a1b83a
FILE_COUNT=23

echo "XAUUSD Signal Bot - pembaruan"
echo "========================================"

if [ ! -d .git ]; then
  echo "  [X] Bukan folder repo git."
  echo "      Posisi Anda sekarang: $(pwd)"
  exit 1
fi
echo "  [ok] folder repo : $(pwd)"

BACKUP=""
if [ -f .env ]; then
  BACKUP=$(mktemp)
  cp .env "$BACKUP"
  echo "  [ok] .env         dicadangkan"
else
  echo "  [!]  .env         belum ada"
fi

TMP=$(mktemp -d)
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | tr -d '\n' | base64 -d > "$TMP/p.tgz"

if command -v shasum >/dev/null 2>&1; then
  GOT=$(shasum -a 256 "$TMP/p.tgz" | cut -c1-16)
else
  GOT=$(sha256sum "$TMP/p.tgz" | cut -c1-16)
fi

if [ "$GOT" != "$EXPECTED_SHA" ]; then
  echo "  [X] berkas rusak saat transfer"
  echo "      dapat $GOT, harusnya $EXPECTED_SHA"
  rm -rf "$TMP"
  exit 1
fi
echo "  [ok] integritas   terverifikasi"

tar -xzf "$TMP/p.tgz" -C .
rm -rf "$TMP"

if [ -n "$BACKUP" ]; then
  cp "$BACKUP" .env
  rm -f "$BACKUP"
fi
chmod +x install-macos.sh 2>/dev/null || true

echo "  [ok] $FILE_COUNT berkas ditulis"
echo "========================================"
echo
echo "Berkas kunci:"
for f in .github/workflows/signal.yml .github/workflows/commands.yml telegram_bot.py datafeed.py xau_signal.py; do
  if [ -f "$f" ]; then echo "  [ok] $f"; else echo "  [X]  $f HILANG"; fi
done

echo
echo "Langkah berikutnya:"
echo "  1. python3 datafeed.py"
echo "  2. git add -A && git status      (pastikan .env TIDAK muncul)"
echo "  3. git commit -m 'feat: perintah Telegram'"
echo "  4. git push"
exit 0

