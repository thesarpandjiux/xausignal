#!/bin/bash
set -euo pipefail
EXPECTED_SHA=9ee57b1b3e4c85fb
FILE_COUNT=29
echo "XAUUSD Signal Bot - pembaruan"
echo "========================================"
if [ ! -d .git ]; then echo "  [X] Bukan folder repo git. Posisi: $(pwd)"; exit 1; fi
echo "  [ok] folder repo : $(pwd)"
BACKUP=""
if [ -f .env ]; then BACKUP=$(mktemp); cp .env "$BACKUP"; echo "  [ok] .env         dicadangkan";
else echo "  [!]  .env         belum ada"; fi
TMP=$(mktemp -d)
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | tr -d '\n' | base64 -d > "$TMP/p.tgz"
if command -v shasum >/dev/null 2>&1; then GOT=$(shasum -a 256 "$TMP/p.tgz" | cut -c1-16)
else GOT=$(sha256sum "$TMP/p.tgz" | cut -c1-16); fi
if [ "$GOT" != "$EXPECTED_SHA" ]; then
  echo "  [X] berkas rusak: dapat $GOT, harusnya $EXPECTED_SHA"; rm -rf "$TMP"; exit 1; fi
echo "  [ok] integritas   terverifikasi"
tar -xzf "$TMP/p.tgz" -C .
rm -rf "$TMP"
if [ -n "$BACKUP" ]; then cp "$BACKUP" .env; rm -f "$BACKUP"; fi
chmod +x listen.sh install-macos.sh worker/setup.sh 2>/dev/null || true
echo "  [ok] $FILE_COUNT berkas ditulis"
echo "========================================"
echo
echo "  Berikutnya, dua perintah:"
echo "    git add -A && git commit -m 'feat: worker' && git push"
echo "    cd worker && ./setup.sh"
exit 0

